/* Language: saved preference > browser language > English */
function detectLang() {
  let saved = null;
  try { saved = localStorage.getItem('rs1-lang'); } catch (e) { /* storage not available */ }
  if (saved && I18N[saved]) return saved;
  const prefs = navigator.languages && navigator.languages.length
    ? navigator.languages : [navigator.language || 'en'];
  for (const p of prefs) {
    const code = String(p).toLowerCase().split('-')[0];
    if (I18N[code]) return code;
  }
  return 'en';
}

export let lang = detectLang();

export function t(key, ...args) {
  let s = (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
  args.forEach((a, i) => { s = s.split('{' + i + '}').join(a); });
  return s;
}

export function toggleLang() {
  lang = lang === 'en' ? 'es' : 'en';
  localStorage.setItem('rs1-lang', lang);
}
